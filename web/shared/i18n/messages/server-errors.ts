/**
 * Translates an error message from the server into the current language; unknown messages stay as they are.
 * @param message - The English message from the server's error response.
 */
export function translateServerMessage(message: string): string {
  return message in serverErrors.en ? translate(serverErrors, message as keyof typeof serverErrors.en) : message;
}
